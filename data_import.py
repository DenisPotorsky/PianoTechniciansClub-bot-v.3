class DataImporter:
    """Класс для импорта данных о брендах"""

    def __init__(self, db: Database):
        self.db = db
        self.stats = {"brands": 0, "ranges": 0}

    async def import_brands(self, brands_data: dict, clear_existing: bool = True) -> dict:
        """
        Импорт брендов в базу данных

        Args:
            brands_data: Словарь с данными о брендах
            clear_existing: Очистить существующие данные перед импортом
        """
        logger.info("🚀 Начинаем импорт данных о брендах...")

        if clear_existing:
            await self.db.clear_brands_data()
            logger.info("🗑️ Существующие данные очищены")

        for brand_name, brand_info in brands_data.items():
            try:
                # Добавляем бренд
                brand_id = await self.db.add_brand(
                    name=brand_name,
                    country=brand_info.get('country', ''),
                    info=brand_info.get('info', ''),
                    brand_type=brand_info.get('type', 'foreign')
                )
                self.stats["brands"] += 1

                # Добавляем диапазоны
                ranges = brand_info.get('ranges', [])
                for serial_start, serial_end, year in ranges:
                    await self.db.add_serial_range(
                        brand_id=brand_id,
                        serial_start=serial_start,
                        serial_end=serial_end,
                        year=year
                    )
                    self.stats["ranges"] += 1

                logger.info(f"✅ Импортирован бренд: {brand_name} ({len(ranges)} диапазонов)")

            except Exception as e:
                logger.error(f"❌ Ошибка импорта бренда {brand_name}: {e}")

        logger.info(f"✅ Импорт завершен! Брендов: {self.stats['brands']}, Диапазонов: {self.stats['ranges']}")
        return self.stats


